def simple_collision_element_count(mesh):
    """Count stored simple-collision elements. str(KAggregateGeom) cannot."""
    body = mesh.get_editor_property("body_setup")
    geom = body.get_editor_property("agg_geom")
    total = 0
    for prop in ("box_elems", "sphere_elems", "convex_elems",
                 "tapered_capsule_elems", "level_set_elems"):
        try:
            total += len(geom.get_editor_property(prop))
        except Exception:  # noqa: BLE001 - a missing array is simply zero
            pass
    return total


def import_structure(label, materials):
    """Import one FBX, force simple collision, override its material slots."""
    fbx = os.path.join(ART_DIR, "SS_RedGum_{}.fbx".format(label))
    if not os.path.isfile(fbx):
        report["errors"].append("missing FBX " + fbx)
        return None

    task = unreal.AssetImportTask()
    task.set_editor_property("filename", fbx)
    task.set_editor_property("destination_path", DEST)
    task.set_editor_property("automated", True)
    task.set_editor_property("replace_existing", True)
    task.set_editor_property("save", True)

    opts = unreal.FbxImportUI()
    for prop, value in (("import_mesh", True),
                        ("import_as_skeletal", False),
                        ("import_animations", False),
                        ("import_materials", True),
                        ("import_textures", False)):
        try:
            opts.set_editor_property(prop, value)
        except Exception as exc:  # noqa: BLE001
            warn("FbxImportUI.{}: {}".format(prop, exc))
    try:
        smi = opts.get_editor_property("static_mesh_import_data")
        smi.set_editor_property("combine_meshes", True)
        smi.set_editor_property("auto_generate_collision", True)
        smi.set_editor_property("generate_lightmap_u_vs", False)
    except Exception as exc:  # noqa: BLE001
        warn("static_mesh_import_data: {}".format(exc))
    task.set_editor_property("options", opts)

    unreal.AssetToolsHelpers.get_asset_tools().import_asset_tasks([task])
    imported = list(task.get_editor_property("imported_object_paths") or [])
    if not imported:
        report["errors"].append("import produced nothing for " + label)
        return None

    path = "{}/SS_RedGum_{}".format(DEST, label)
    mesh = unreal.load_asset(path)
    if not isinstance(mesh, unreal.StaticMesh):
        report["errors"].append("no StaticMesh at " + path)
        return None

    # CTF_USE_DEFAULT, written and read back. See R-10 in the docstring.
    flag, applied = unreal.CollisionTraceFlag.CTF_USE_DEFAULT, ""
    try:
        body = mesh.get_editor_property("body_setup")
        body.set_editor_property("collision_trace_flag", flag)
        applied = str(body.get_editor_property("collision_trace_flag"))
    except Exception as exc:  # noqa: BLE001
        report["errors"].append("{}: collision_trace_flag: {}".format(label, exc))
    if "CTF_USE_DEFAULT" not in applied:
        report["errors"].append("{}: trace flag is {!r}, not CTF_USE_DEFAULT".format(label, applied))

    # Slot override by name. The FBX carries slot names from the Blender
    # materials, so this is a lookup rather than an ordering assumption.
    #
    # StaticMesh.Materials is a protected property on 5.8 and raises on read;
    # StaticMaterials is the array that actually holds the slot names, so the
    # slot list is read from there and written back through set_material.
    slots = list(mesh.get_editor_property("static_materials"))
    assigned, unresolved = [], []
    for index, sm in enumerate(slots):
        slot_name = str(sm.get_editor_property("material_slot_name"))
        key = slot_name.replace("SS_RedGum_", "").strip("_")
        target = pack_material(key) or materials.get(key)
        if target is None:
            unresolved.append(slot_name)
            continue
        mesh.set_material(index, target)
        assigned.append(slot_name)
    if unresolved:
        warn("{}: unresolved slots {}".format(label, unresolved))

    # Drop the empty instance constants the FBX importer created; every slot now
    # points at an authored material and the leftovers are unreferenced clutter.
    for obj_path in imported:
        if obj_path == path:
            continue
        asset = unreal.load_asset(obj_path)
        if isinstance(asset, unreal.MaterialInterface):
            unreal.EditorAssetLibrary.delete_asset(obj_path)

    unreal.EditorAssetLibrary.save_loaded_asset(mesh)
    report["structures"].append({
        "name": label,
        "path": path,
        "trace_flag": applied,
        "simple_collision_elements": simple_collision_element_count(mesh),
        "slots_assigned": assigned,
        "slots_unresolved": unresolved,
    })
    return mesh


