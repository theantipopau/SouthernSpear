"""
Southern Spear - import and place the original Red Gum homestead (class F).

Places the compound generated by Tools/Blender/redgum_homestead.py on
/Game/Maps/L_RedGum_01 and authors its materials. Idempotent: on rerun it
removes only the actors it owns (label prefix SS_RedGum_Homestead_), so it can
be re-run after a Blender change without duplicating the station or touching
the pack's trees, fences or the objectives.

Why it is a separate pass from the dressing (expand_redgum.py): the dressing
pass owns everything with the SS_RedGum_Dress_v1_ prefix and deletes exactly
that set on rerun. If the homestead shared that prefix, a dressing rerun would
delete the station and then not put it back. Separate prefixes, separate
lifecycles, and neither pass can silently eat the other's work.

COLLISION POLICY, PER STRUCTURE - this is the part that is easy to get wrong

    farmhouse, shearing shed, hut, water tank : SOLID. These are the centre
        objective's hard cover and must be in the navmesh.
    stock pens, windmill : NO COLLISION. A one-piece convex hull around the
        joined stock-pen mesh would be a solid 18 x 13 m block - an invisible
        wall in the middle of the yard with the rails nowhere near its surface.
        The windmill has the same problem in miniature. Both are also thin
        enough that the honest options are "no collision" (what the pack's wire
        fences already do, ADR-022) or per-rail colliders, and per-rail
        colliders are a later pass, not a guess made in a placement script.

THE FAITHFUL-TRACE-FLAG LESSON (R-10)

The mesh is asked for SIMPLE collision at import and the trace flag is then
written unconditionally and read back. dress_dryriver.py shipped a run that
reported ok while the write silently did nothing, because the enum member it
asked for did not exist. So: assert the read-back, and count the simple
collision elements, which is what distinguishes "the mesh has no collision"
from "str(KAggregateGeom) is an opaque pointer and tells you nothing".

REPORT: Build/redgum_homestead_report.json (git-ignored).
"""

import csv
import json
import math
import os
import traceback

import unreal

PROJECT_DIR = unreal.Paths.convert_relative_path_to_full(unreal.Paths.project_dir())
MAP = "/Game/Maps/L_RedGum_01"
ART_DIR = os.path.join(PROJECT_DIR, "Content", "Art", "Environment", "RedGum")
CSV_PATH = os.path.join(ART_DIR, "SS_RedGum_Homestead_Layout.csv")
DEST = "/Game/Art/Environment/RedGum"
MAT_DEST = DEST + "/Materials"
REPORT = os.path.join(PROJECT_DIR, "Build", "redgum_homestead_report.json")

PREFIX = "SS_RedGum_Homestead_"
FOLDER = unreal.Name("RedGum/Homestead")

# Slot name authored in Blender (SS_RedGum_<Slot>) -> authored UE material.
# Base colours are dry-country: dust-pale green boards, red-oxide iron,
# silvered timber, dark glass, galvanised metal. No texture is sampled from
# anywhere; these are constants, so the station carries no third-party licence
# dependency of any kind (L-0011 class F).
MATERIALS = {
    "Wall":   ((0.352, 0.372, 0.302), 0.78, 0.0),   # r, g, b, roughness, metallic
    "Roof":   ((0.196, 0.070, 0.042), 0.62, 0.25),
    "Timber": ((0.185, 0.150, 0.110), 0.85, 0.0),
    "Glass":  ((0.014, 0.020, 0.024), 0.10, 0.0),
    "Metal":  ((0.330, 0.348, 0.360), 0.38, 0.85),
}

# Textured look (Session 041, producer: "very poor quality, just a block"): where the Singapore Canal pack
# (L-0016 Fab licence) is installed, its weathered materials replace the constants above; the meshes carry
# box-projected UVs from redgum_homestead.py. Without the pack the constants are used, as before.
PACK_MATERIALS = {
    "Wall": "/Game/Singapore_Canal/Materials/MI_WoodPainted_01",
    "Roof": "/Game/Art/Environment/Fab/CorrugatedIron/MI_SS_CorrugatedIron",
    "Metal": "/Game/Art/Environment/Fab/CorrugatedIron/MI_SS_CorrugatedIron",
    "Timber": "/Game/Singapore_Canal/Materials/MI_WoodOldRaw_01",
}


def pack_material(key):
    path = PACK_MATERIALS.get(key)
    if not path or not unreal.EditorAssetLibrary.does_asset_exist(path):
        return None
    m = unreal.load_asset(path)
    return m if isinstance(m, unreal.MaterialInterface) else None


# Solid where the structure is meant to stop a player, open where a hull would
# be a lie. See the module docstring.
NO_COLLISION = {"StockPens", "Windmill"}

# The farmhouse pad is the largest footprint (12 x 8 m plus a 2.6 m verandah).
# Used only to report the yard's clear extent, not to place anything.
actor_sub = unreal.get_editor_subsystem(unreal.EditorActorSubsystem)
report = {"ok": False, "map": MAP, "steps": [], "materials": {},
          "structures": [], "errors": [], "warnings": []}


def step(name, ok, detail=""):
    report["steps"].append({"step": name, "ok": bool(ok), "detail": str(detail)})
    unreal.log("[RedGumHomestead] {} {} {}".format("OK  " if ok else "FAIL", name, detail))
    return bool(ok)


def warn(msg):
    report["warnings"].append(str(msg))
    unreal.log("[RedGumHomestead] WARN {}".format(msg))


