def ground_z(world, x, y):
    hit = unreal.SystemLibrary.line_trace_single(
        world, unreal.Vector(x, y, 50000.0), unreal.Vector(x, y, -50000.0),
        unreal.TraceTypeQuery.TRACE_TYPE_QUERY1, True, [],
        unreal.DrawDebugTrace.NONE, True)
    if hit is None:
        return None
    hr = hit[1] if isinstance(hit, (list, tuple)) and len(hit) > 1 and hit[0] else hit
    try:
        return hr.to_dict()["impact_point"].z
    except Exception:  # noqa: BLE001
        return None


def ground_z_median(world, x, y, half_x, half_y, cols=5, rows=4, margin=0.0):
    """Median ground height over a footprint, in cm.

    A single centre trace is not a building's ground height. On Red Gum it
    returned the top of a gum tree standing inside the footprint and lifted the
    shearing shed 1.66 m into the air, and a centre trace through a placed
    building returns its own roof. Sampling a grid across the footprint and
    taking the median fixes the first; the seating check deliberately samples
    OUTSIDE the footprint so it stays an independent measurement of the second.
    """
    samples = []
    for r in range(rows):
        for c in range(cols):
            px = x + (half_x + margin) * ((c / float(cols - 1)) * 2.0 - 1.0)
            py = y + (half_y + margin) * ((r / float(rows - 1)) * 2.0 - 1.0)
            gz = ground_z(world, px, py)
            if gz is not None:
                samples.append(gz)
    if not samples:
        return None
    samples.sort()
    mid = len(samples) // 2
    if len(samples) % 2:
        return samples[mid]
    return (samples[mid - 1] + samples[mid]) / 2.0


def remove_owned_actors():
    removed = 0
    for actor in actor_sub.get_all_level_actors():
        if actor.get_actor_label().startswith(PREFIX):
            actor_sub.destroy_actor(actor)
            removed += 1
    report["removed_previous_pass"] = removed
    return removed


def objective_b(world):
    """The centre objective, found by label rather than hard-coded coordinates.

    Hard-coding would silently move the station if layout_objectives.py ever
    re-lays the objectives, which is exactly the kind of coupling that makes a
    map look broken a month later.
    """
    objectives = unreal.GameplayStatics.get_all_actors_of_class(world, unreal.SSObjectiveActor)
    for actor in objectives:
        if "ObjB" in actor.get_actor_label():
            return actor
    for actor in objectives:
        if "Homestead" in actor.get_actor_label():
            return actor
    return objectives[1] if len(objectives) > 1 else None


def place(meshes, world, anchor, rows):
    """Place each structure at its CSV offset from the anchor, snapped to ground.

    Blender-space metres to UE centimetres, with Y negated and yaw flipped to
    match: the FBX is exported axis_forward='-Z', axis_up='Y', which maps
    Blender +Y to UE -Y. The same handedness rule is applied by
    dress_dryriver.py, and both passes agree on it deliberately.
    """
    placed = 0
    for row in rows:
        name, structure = row["name"], row["structure"]
        mesh = meshes.get(name)
        if mesh is None:
            continue
        x_m, y_m = float(row["x_m"]), float(row["y_m"])
        yaw = -float(row["yaw_deg"])
        scale = float(row.get("scale") or 1.0)

        loc = unreal.Vector(anchor.x + x_m * 100.0, anchor.y - y_m * 100.0, 0.0)

        # The CSV carries the measured footprint, so the ground height is the
        # median under the whole building rather than one point that might be a
        # tree, a log or the building itself.
        half_x = float(row.get("half_x_m") or 2.0) * 100.0 * scale
        half_y = float(row.get("half_y_m") or 2.0) * 100.0 * scale
        base_z_m = row.get("base_z_m")
        if base_z_m is not None and abs(float(base_z_m)) > 0.05:
            report["errors"].append(
                "{}: authored base is at z={} m, not 0; it would sit {} m off the ground"
                .format(name, base_z_m, base_z_m))
        z = ground_z_median(world, loc.x, loc.y, half_x, half_y)
        if z is None:
            warn("no ground hit under {} ({:.0f}, {:.0f})".format(name, loc.x, loc.y))
            continue
        loc.z = z

        # spawn_actor_from_object refuses a mesh imported in this same session
        # ("SpawnActorFromObject. No actor was spawned." with no further
        # detail), so spawn the actor class and hand it the mesh instead - the
        # same route dress_dryriver.py uses successfully.
        actor = actor_sub.spawn_actor_from_class(
            unreal.StaticMeshActor, loc, unreal.Rotator(roll=0.0, pitch=0.0, yaw=yaw))
        if not actor:
            report["errors"].append("spawn returned None for " + name)
            continue
        actor.static_mesh_component.set_static_mesh(mesh)
        actor.set_actor_label(PREFIX + name)
        try:
            actor.set_folder_path(FOLDER)
        except Exception:  # noqa: BLE001 - foldering is cosmetic
            pass
        actor.set_actor_scale3d(unreal.Vector(scale, scale, scale))

        collide = name not in NO_COLLISION
        actor.set_actor_enable_collision(collide)
        actor.static_mesh_component.set_collision_profile_name(
            "BlockAll" if collide else "NoCollision")

        # No vertical offset. Every structure in redgum_homestead.py is authored
        # with its base exactly at local z = 0 (slab bottoms, post feet and leg
        # feet all start at 0), so the traced ground height IS the actor height.
        #
        # Two earlier versions tried to compensate using the mesh's own bounds
        # and both buried the station: asking a just-imported asset for its
        # bounds in the same session returns a degenerate box, so the computed
        # offset was a full height of earth. The verify step below measures the
        # actor's real world bounds against the ground instead, which is the
        # quantity that matters - if a future Blender edit breaks the
        # base-at-origin convention, that step fails loudly.
        actor.set_actor_location(loc, False, False)

        for entry in report["structures"]:
            if entry["name"] == name:
                origin_b, extent_b = actor.get_actor_bounds(False)
                entry["location_cm"] = [round(actor.get_actor_location().x),
                                        round(actor.get_actor_location().y),
                                        round(actor.get_actor_location().z)]
                entry["world_bounds_cm"] = {
                    "min": [round(origin_b.x - extent_b.x), round(origin_b.y - extent_b.y),
                            round(origin_b.z - extent_b.z)],
                    "max": [round(origin_b.x + extent_b.x), round(origin_b.y + extent_b.y),
                            round(origin_b.z + extent_b.z)],
                }
                entry["collision"] = collide
                entry["structure"] = structure
        placed += 1
    return placed


def verify_solid(world, meshes, rows):
    """Prove the solid structures block a trace AND sit on the ground.

    Two separate failure modes, measured separately. A trace hit alone is not
    enough: a structure buried up to its roofline is still a trace hit, and
    that is exactly what a wrong vertical offset produces. The seating check
    is the one that catches it.
    """
    checked = 0
    unseated = []
    for actor in actor_sub.get_all_level_actors():
        label = actor.get_actor_label()
        if not label.startswith(PREFIX):
            continue
        name = label[len(PREFIX):]
        if name in NO_COLLISION:
            continue
        loc = actor.get_actor_location()
        origin, extent = actor.get_actor_bounds(False)
        # Probe a small cross inside the footprint; the middle of a stock pen
        # is empty ground, so a single centre trace would under-report.
        probes = 0
        hits = 0
        for dx, dy in ((0.0, 0.0), (extent.x * 0.5, 0.0), (-extent.x * 0.5, 0.0),
                       (0.0, extent.y * 0.5), (0.0, -extent.y * 0.5)):
            res = unreal.SystemLibrary.line_trace_single(
                world, unreal.Vector(origin.x + dx, origin.y + dy, loc.z + 800.0),
                unreal.Vector(origin.x + dx, origin.y + dy, loc.z - 800.0),
                unreal.TraceTypeQuery.TRACE_TYPE_QUERY1, True, [],
                unreal.DrawDebugTrace.NONE, True)
            hit = res[0] if isinstance(res, (list, tuple)) and res else res is not None
            probes += 1
            hits += 1 if hit else 0
        checked += 1

        # Seating: the actor's world bounds bottom against the ground just
        # OUTSIDE its footprint, measured on a ring so it is independent of the
        # median the placement used. Tracing down through the centre of a
        # placed building returns its own roof, which reported every structure
        # as buried by its own height; sampling outside is immune to that.
        # +-0.35 m is slack for land that is not flat under a 16 m shed, but far
        # tighter than a float.
        seated_m = None
        ring = []
        ring_pts = []
        for i in range(8):
            ang = math.tau * i / 8.0
            ring_pts.append((math.cos(ang), math.sin(ang)))
        for dx, dy in ring_pts:
            gz = ground_z(world, origin.x + dx * (extent.x + 120.0),
                          origin.y + dy * (extent.y + 120.0))
            if gz is not None:
                ring.append(gz)
        if ring:
            ring.sort()
            gz = ring[len(ring) // 2] if len(ring) % 2 else (
                ring[len(ring) // 2 - 1] + ring[len(ring) // 2]) / 2.0
            seated_m = round((origin.z - extent.z - gz) / 100.0, 2)
            if abs(seated_m) > 0.35:
                unseated.append("{} {}".format(name, seated_m))

        for entry in report["structures"]:
            if entry["name"] == name:
                entry["trace_probes"] = "{} of {}".format(hits, probes)
                entry["solid"] = hits > 0
                entry["base_minus_ground_m"] = seated_m
    report["unseated"] = unseated
    return checked


# ---------------------------------------------------------------------------

def main():
    if not os.path.isfile(CSV_PATH):
        report["errors"].append("missing layout CSV " + CSV_PATH)
        return
    with open(CSV_PATH, "r", encoding="utf-8") as fh:
        rows = list(csv.DictReader(fh))
    step("read_layout_csv", bool(rows), "{} rows".format(len(rows)))

    world = unreal.EditorLoadingAndSavingUtils.load_map(MAP)
    if not step("load_map", world is not None, MAP):
        return

    materials = build_materials()
    if len(materials) != len(MATERIALS):
        return

    meshes = {}
    for row in rows:
        mesh = import_structure(row["name"], materials)
        if mesh is not None:
            meshes[row["name"]] = mesh
    step("import_structures", len(meshes) == len(rows),
        "{} of {} imported".format(len(meshes), len(rows)))
    report["materials"] = {k: v.get_path_name() for k, v in materials.items()}

    anchor_actor = objective_b(world)
    if not step("find_objective_b", anchor_actor is not None,
                 anchor_actor.get_actor_label() if anchor_actor else "none"):
        return
    anchor = anchor_actor.get_actor_location()
    report["anchor_cm"] = [round(anchor.x), round(anchor.y), round(anchor.z)]
    report["anchor_label"] = anchor_actor.get_actor_label()

    remove_owned_actors()
    placed = place(meshes, world, anchor, rows)
    step("place_structures", placed == len(rows),
         "{} of {} placed".format(placed, len(rows)))

    checked = verify_solid(world, meshes, rows)
    solid = [e for e in report["structures"] if e.get("collision")]
    missing = [e["name"] for e in solid if not e.get("solid")]
    step("verify_collision", not missing,
         "{} solid structures traced, missing {}".format(len(solid), missing or "none"))
    step("verify_ground_seating", not report["unseated"],
         "base-to-ground deviation over 0.35 m: {}".format(report["unseated"] or "none"))
    report["verified_solid_count"] = checked

    saved = bool(unreal.get_editor_subsystem(unreal.LevelEditorSubsystem).save_current_level())
    step("save_map", saved, MAP)
    report["ok"] = all(s["ok"] for s in report["steps"])


try:
    main()
except Exception:  # noqa: BLE001
    report["errors"].append(traceback.format_exc())
    unreal.log_error("[RedGumHomestead] raised:\n" + traceback.format_exc())
finally:
    os.makedirs(os.path.dirname(REPORT), exist_ok=True)
    with open(REPORT, "w", encoding="utf-8") as fh:
        json.dump(report, fh, indent=2, default=str)
    unreal.log("[RedGumHomestead] complete ok={} report={}".format(report.get("ok"), REPORT))
