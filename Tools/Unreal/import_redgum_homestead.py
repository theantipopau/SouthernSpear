def build_materials():
    """Author the five station materials as constants on fresh material assets.

    Created with MaterialFactoryNew and rebuilt every run, because a half-built
    material (colour wired, roughness not) is the classic silent-no-op and a
    map full of wrong-coloured buildings is worse than no buildings.
    """
    mel = unreal.MaterialEditingLibrary
    made = {}
    for slot, (rgb, rough, metal) in MATERIALS.items():
        name = "M_SS_RedGum_" + slot
        path = MAT_DEST + "/" + name
        if unreal.EditorAssetLibrary.does_asset_exist(path):
            unreal.EditorAssetLibrary.delete_asset(path)
        factory = unreal.MaterialFactoryNew()
        mat = unreal.AssetToolsHelpers.get_asset_tools().create_asset(
            name, MAT_DEST, unreal.Material, factory)
        if mat is None:
            report["errors"].append("could not create " + path)
            continue

        def constant(cls, y, value, prop="r"):
            expr = mel.create_material_expression(mat, cls, -400, y)
            expr.set_editor_property(prop, value)
            return expr

        base = mel.create_material_expression(
            mat, unreal.MaterialExpressionConstant3Vector, -700, 120)
        base.set_editor_property("constant", unreal.LinearColor(rgb[0], rgb[1], rgb[2], 1.0))
        mel.connect_material_property(base, "", unreal.MaterialProperty.MP_BASE_COLOR)
        mel.connect_material_property(
            constant(unreal.MaterialExpressionConstant, -60, rough), "",
            unreal.MaterialProperty.MP_ROUGHNESS)
        mel.connect_material_property(
            constant(unreal.MaterialExpressionConstant, -260, metal), "",
            unreal.MaterialProperty.MP_METALLIC)
        mel.recompile_material(mat)
        unreal.EditorAssetLibrary.save_loaded_asset(mat)
        made[slot] = mat
    # Return the assets, not the step verdict: step() returns a bool, and
    # returning that here made main()'s len(materials) raise on a bool.
    step("author_materials", len(made) == len(MATERIALS),
         "{} of {}".format(len(made), len(MATERIALS)))
    return made


